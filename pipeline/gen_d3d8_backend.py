"""gen_d3d8_backend.py -- xi_d3d8_backend.hpp: one interface every Direct3D 8 call in the tree goes through (#136).

The tree calls Direct3D 8 the way the game does, through each object's vtable: `dev->lpVtbl->SetRenderState(dev, ...)`
or the SDK's C++ form `dev->SetRenderState(...)` (xi_d3d8.hpp's inline wrappers, which call through lpVtbl). Built with
XI_BACKEND, the name IFooVtbl is the proxy this header defines, and the SDK's vtable struct is IFooVtbl_sdk
(xi_d3d8.hpp's XI_SDKVTBL): `lpVtbl`, and every local the text declares with the vtable's type, is a proxy pointer. The
proxy is as large as the vtable (a pointer step over it is unchanged) and has no data the code reads. A slot read as a
value and called through a cast (`((fn)dev->lpVtbl->Clear)(...)`, Hex-Rays' form where the call's prototype differs)
is written `lpVtbl->XI_SLOT(Clear)` (hx2clean.py): the slot itself without XI_BACKEND, the routed slot with it. The
object's memory is unchanged (its first dword is still the vtable's address, which the proxy's `this` is);
only the call is routed: each proxy method calls through `xi_backend[k]` (k: the interface's index below) when it is
set, and through the object's own vtable when it is null. So with no backend installed every call is the call the
tree made before, and a backend (a D3D11 renderer) fills an entry with a table of its own: a copy of the vtable it
takes over, with the methods it implements replaced. Every method of every interface goes through it, whatever the
caller; the vtable layouts are the SDK's (xi_d3d8.hpp, from MinGW-w64 d3d8.h).

    python3 pipeline/gen_d3d8_backend.py pipeline/xi_d3d8.hpp pipeline/xi_d3d8_backend.hpp"""
import re, sys


def main(src, out):
    s = open(src).read()
    vt = re.findall(r'struct XI_SDKVTBL\((IDirect3D\w*8)\) \{\n(.*?)\n\};', s, re.S)
    lines = ['// xi_d3d8_backend.hpp -- generated by pipeline/gen_d3d8_backend.py from xi_d3d8.hpp; do not edit.',
             '// ' + __doc__.split('\n\n')[0].split(' -- ')[1],
             '#pragma once', '#ifdef XI_BACKEND',
             '// xi_backend[k]: the table interface k calls through, or null for the object\'s own vtable (rt.c defines it;',
             '// xi_set_backend sets it). The indices:']
    for k, (name, _) in enumerate(vt): lines.append('#define XI_BACKEND_%s %d' % (name, k))
    lines += ['#define XI_BACKEND_COUNT %d' % len(vt), 'extern "C" void *xi_backend[XI_BACKEND_COUNT];', '']
    for k, (name, body) in enumerate(vt):
        lines.append('struct %sVtbl {' % name)
        lines.append('    char xi_size[sizeof(%sVtbl_sdk)];   // as large as the vtable; never read' % name)
        lines.append('    const %sVtbl_sdk *xi_v() const { return xi_backend[%d] ? static_cast<const %sVtbl_sdk *>(xi_backend[%d])'
                     ' : reinterpret_cast<const %sVtbl_sdk *>(this); }' % (name, k, name, k, name))
        for m in re.finditer(r'^\s*(.+?) \(__stdcall \*(\w+)\)\((.*)\);$', body, re.M):
            ret, meth, params = m.groups()
            ps = [p.strip() for p in params.split(',')]
            names = [re.search(r'(\w+)\s*$', p).group(1) for p in ps]
            lines.append('    %s %s(%s) const { return xi_v()->%s(%s); }' % (ret, meth, ', '.join(ps), meth, ', '.join(names)))
            lines.append('    void *slot_%s() const { return reinterpret_cast<void *>(xi_v()->%s); }' % (meth, meth))
        lines.append('};')
    lines += ['#define XI_SLOT(m) slot_##m()', '#else', '#define XI_SLOT(m) m', '#endif', '']
    open(out, 'w', newline='\n').write('\n'.join(lines))
    print('%d interfaces, %d methods' % (len(vt), sum(len(re.findall(r'__stdcall \*', b)) for _, b in vt)))


if __name__ == '__main__':
    main(*sys.argv[1:3])
