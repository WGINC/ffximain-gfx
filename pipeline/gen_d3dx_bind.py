"""gen_d3dx_bind.py -- d3dx81_bind.hpp: every public D3DX 8.1 API entry point statically linked into
the game, bound to its game address. Prototypes come from the SDK's own d3dx8*.h (not copied here):
in a hybrid build, d3dx81::Name(...) calls the copy inside FFXiMain; in a standalone build define
XI_D3DX_LINK_SDK and the same calls resolve to d3dx8.lib."""
import json, re, glob, os
D3DX = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'd3dx')
# DX81_INCLUDE: the DirectX 8.1 SDK include directory (not part of this repo)
man = json.load(open(os.path.join(D3DX, 'd3dx81_manifest.json')))
hdr = ''.join(open(f, errors='replace').read() for f in glob.glob(os.path.join(os.environ['DX81_INCLUDE'], 'd3dx8*.h')))
public = set(re.findall(r'\b(D3DX\w+)\s*\(\s*\n?', hdr)) & set(re.findall(r'WINAPI\s+(D3DX\w+)', hdr))
rows, inline = [], []
for ea, v in sorted(man.items(), key=lambda kv: int(kv[0], 16)):
    n = v['name']
    if n in public and v['symbol'].startswith('_'):        # extern "C" stdcall export: _Name@N
        rows.append((n, int(ea, 16), v['bytes_compared'], v['how']))
    elif n in public: inline.append((n, int(ea, 16)))
seen = {}
for n, ea, b, how in rows: seen.setdefault(n, (ea, b, how))
L = ['// d3dx81_bind.hpp -- generated by gen_d3dx_bind.py. Addresses: FFXiMain.dll build 2026-09-03.',
     '// Byte-matched against d3dx8.lib, DirectX 8.1 SDK (16 Oct 2001). Prototypes: the SDK\'s d3dx8.h.',
     '#pragma once', '#include <d3dx8.h>', 'namespace d3dx81 {',
     '#ifdef XI_D3DX_LINK_SDK', '#define XI_D3DX(name, ea) using ::name;', '#else',
     '#define XI_D3DX(name, ea) static decltype(&::name) const name = reinterpret_cast<decltype(&::name)>(ea##u);',
     '#endif']
for n, (ea, b, how) in sorted(seen.items(), key=lambda kv: kv[1][0]):
    L.append('XI_D3DX(%-40s 0x%08X)  // %d bytes, %s' % (n + ',', ea, b, how))
L += ['#undef XI_D3DX', '} // namespace d3dx81']
open(os.path.join(D3DX, 'd3dx81_bind.hpp'), 'w').write('\n'.join(L) + '\n')
print(len(public), 'public API in SDK headers;', len(seen), 'bound;', len(inline), 'inline/C++ copies not bound', inline[:6])
