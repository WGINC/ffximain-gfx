"""make_measure.py -- xikit_measure.txt: what the kit's call timing (imports=, callsites=; docs/KIT.md) may wrap.

Every line comes from the analysed build's own code ($FFXI_DLL), nothing from names or guesses:
  I SLOT DLL NAME             an import slot of FFXiMain.dll (its import table: the slot the loader fills with
                              DLL!NAME). The kit wraps the slot only if the live slot holds what DLL!NAME resolves to,
                              or an address inside DLL (another tool's hook is left alone, logged).
  S SITE TARGET LEVEL CALLER  a direct call (E8 rel32, decoded with capstone from the function's chunks in
                              data/func_extents.json) at SITE to TARGET. The kit rewrites the rel32 only if the live
                              bytes are E8 and the rel32 reaches TARGET's live address.
LEVEL: 0 = the main loop (CApp_RunMainLoop's frame loop 0x100015BF..0x100016B5) and App_RenderFrameMaskedFPU
(0x10001B50); 1 = the functions level 0 calls (Frame_Render 0x10011A00, the game mode's update 0x100DAF30, ...);
2 = the functions level 1 calls; 3 = the functions level 2 calls. A function's sites are listed at the lowest level
it is reached at. The names are labels for the report only (disasm.py's: the export, data/names_pending_idb.json).

    python3 make_measure.py OUT.txt          (uses $FFXI_DLL)"""
import json, os, re, sys
import pefile
from capstone import Cs, CS_ARCH_X86, CS_MODE_32

H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(H, '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'pipeline'))
from disasm import names

LOOP = (0x100015BF, 0x100016B5)          # CApp_RunMainLoop's frame loop (the PeekMessage loop that renders frames)
ROOTS0 = [0x10001B50]                    # App_RenderFrameMaskedFPU: calls Frame_Render, then the game mode's update


def main(out):
    pe = pefile.PE(os.environ['FFXI_DLL'])
    base = pe.OPTIONAL_HEADER.ImageBase; img = pe.get_memory_mapped_image()
    ext = json.load(open(os.path.join(ROOT, 'data', 'func_extents.json')))
    starts = {int(k, 16) for k in ext}
    md = Cs(CS_ARCH_X86, CS_MODE_32); N = names()
    lines = ['# xikit_measure.txt -- generated by kit/xikit/make_measure.py from FFXiMain.dll TimeDateStamp %08X; do not edit'
             % pe.FILE_HEADER.TimeDateStamp]
    nimp = 0
    for e in pe.DIRECTORY_ENTRY_IMPORT:
        for i in e.imports:
            if not i.name: continue
            lines.append('I %08X %s %s' % (i.address, e.dll.decode().lower(), i.name.decode())); nimp += 1

    def calls(chunks, entry):
        """direct calls on the instructions reached from the entry by flow (fallthrough, direct jumps and branches,
        inside the chunks, and a switch's table when the two instructions before its jmp are `cmp idx, N; ja`: the
        bound is the code's own; a ret, any other indirect jmp or int3 ends a path): bytes a linear sweep would decode inside a
        jump table are never reached. Only calls to a function start are kept."""
        ins = {}
        for s, e in chunks:
            for i in md.disasm(img[s - base:e - base], s): ins[i.address] = i
        order = sorted(ins)
        seen, work = {entry}, [entry]
        while work:
            a = work.pop(); i = ins.get(a)
            if i is None: continue
            m = i.mnemonic; nxt = [a + i.size]
            if m.startswith('ret') or m in ('int3', 'hlt', 'ud2'): nxt = []
            elif m == 'jmp':
                nxt = [int(i.op_str, 16)] if i.bytes[0] in (0xE9, 0xEB) else []
                t = re.fullmatch(r'dword ptr \[(e\w\w)\*4 \+ (0x[0-9a-f]+)\]', i.op_str)
                prev = [ins[p] for p in order[max(0, order.index(a) - 2):order.index(a)]]
                if t and len(prev) == 2 and prev[1].mnemonic == 'ja' and prev[0].mnemonic == 'cmp' \
                        and re.fullmatch(t.group(1) + r', (0x[0-9a-f]+|\d+)', prev[0].op_str):
                    n = int(prev[0].op_str.split(', ')[1], 0) + 1      # cmp idx, N; ja: the table has N + 1 entries
                    tab = int(t.group(2), 16)
                    nxt = [int.from_bytes(img[tab - base + 4 * k:tab - base + 4 * k + 4], 'little') for k in range(n)]
            elif m.startswith(('j', 'loop')) and i.op_str.startswith('0x'): nxt.append(int(i.op_str, 16))
            elif m == 'call' and i.bytes[0] == 0xE8 and i.size == 5:
                t = (a + 5 + int.from_bytes(i.bytes[1:5], 'little', signed=True)) & 0xFFFFFFFF
                if t in starts: yield a, t
            for n in nxt:
                if n in ins and n not in seen: seen.add(n); work.append(n)

    seen = set(); sites = []
    frontier = []
    loopf = sorted((a, t) for a, t in calls(ext['0x10001520'], 0x10001520) if LOOP[0] <= a < LOOP[1])
    for f in ROOTS0: frontier.append((f, 0))
    for a, t in loopf: sites.append((a, t, 0, 0x10001520))
    nxt = {t for _, t in loopf if t in starts}
    for f in ROOTS0: seen.add(f)
    for f, lv in frontier:
        for a, t in calls(ext['0x%x' % f], f):
            sites.append((a, t, lv, f))
            if t in starts: nxt.add(t)
    for lv in (1, 2, 3):
        cur = sorted(t for t in nxt if t not in seen); nxt = set()
        for f in cur:
            seen.add(f)
            for a, t in calls(ext['0x%x' % f], f):
                sites.append((a, t, lv, f))
                if t in starts and t not in seen: nxt.add(t)
    done = set()
    for a, t, lv, f in sites:
        if a in done: continue
        done.add(a)
        lines.append('S %08X %08X %d %s %s' % (a, t, lv, N.get(f, 'sub_%X' % f).replace(' ', '_'), N.get(t, 'sub_%X' % t).replace(' ', '_')))
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    by = [sum(1 for _, _, lv, _ in sites if lv == k) for k in range(4)]
    print('%d import slots; %d call sites (level 0: %d, 1: %d, 2: %d, 3: %d)' % (nimp, len(done), *by))


if __name__ == '__main__':
    main(sys.argv[1])
