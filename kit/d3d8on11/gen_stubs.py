"""gen_stubs.py -- d8_gen.h: for each Direct3D 8 interface our device implements, a base class whose every method logs
"not implemented" and fails (D3DERR_INVALIDCALL, or 0 / FALSE / nothing for the methods that return no HRESULT).
The device's classes derive from these and override what they implement, so a method the game calls that is not
implemented yet is found in the log, not guessed (docs/D3D11.md, phase 1). The method lists and signatures come from
the D3D8 header the build compiles against (MinGW-w64's d3d8.h); a method missing here leaves the class abstract and
the build fails, so the vtable order is the header's, not this script's.

    python3 gen_stubs.py [path/to/d3d8.h] > d8_gen.h"""
import re, sys

IFACES = ['IDirect3D8', 'IDirect3DDevice8', 'IDirect3DTexture8', 'IDirect3DCubeTexture8', 'IDirect3DSurface8',
          'IDirect3DVertexBuffer8', 'IDirect3DIndexBuffer8']
FAIL = {'HRESULT': 'return D3DERR_INVALIDCALL;', 'void': 'return;', 'WINBOOL': 'return FALSE;', 'HMONITOR': 'return NULL;',
        'D3DRESOURCETYPE': 'return (D3DRESOURCETYPE)0;'}


def methods(h, iface):
    """The interface's methods in vtable order, its bases' first (DECLARE_INTERFACE_ repeats them in each)."""
    m = re.search(r'DECLARE_INTERFACE_\(%s,\s*\w+\)\s*\{(.*?)\n\};' % iface, h, re.S)
    if not m: sys.exit('gen_stubs: %s not found in the header' % iface)
    out = []
    for g in re.finditer(r'STDMETHOD(?:_\(\s*(\w+)\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\(\s*THIS_?\s*([^;]*?)\)\s*PURE;', m.group(1), re.S):
        out.append((g.group(1) or 'HRESULT', g.group(2) or g.group(3), ' '.join(g.group(4).split())))
    return out


def main():
    hp = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/mingw-w64/include/d3d8.h'
    h = open(hp).read()
    print('// d8_gen.h -- generated by gen_stubs.py from %s; do not edit' % hp.split('/')[-1])
    print('#pragma once\n#include <windows.h>\n#include <d3d8.h>\nvoid d8_notimpl_at(const char *what, void *ra);\n')
    for iface in IFACES:
        ms = methods(h, iface)
        print('// %s: %d methods' % (iface, len(ms)))
        print('struct %s_Stub : public %s {' % (iface, iface))
        for rt, name, args in ms:
            if name in ('QueryInterface', 'AddRef', 'Release'): continue      # every class implements these
            fail = FAIL.get(rt, 'return 0;')
            print('  virtual %s STDMETHODCALLTYPE %s(%s) { d8_notimpl_at("%s::%s", __builtin_return_address(0)); %s }' % (rt, name, args, iface, name, fail))
        print('};\n')


if __name__ == '__main__':
    main()
