"""ffxi_ida_fix.py -- one self-contained pass in IDA 9.4: apply the pipeline's pending data, correct IDA's
stack pointer from measured depths, and re-export the graphics functions.

Generated by pipeline/make_ida_fix.py; the data it needs is embedded below, so this one file can be run
from anywhere: open the FFXiMain_unpacked.dll IDB (save it first, or use a copy), then
File > Script file... > ffxi_ida_fix.py. Steps:
  1. names: names_pending_idb.json (only where the IDB still has the expected placeholder name);
  2. prototypes: type_fixes.json;
  3. the viewport globals 0x104E1B70 and 0x10621904 typed D3DVIEWPORT8 (24 bytes, not pointers);
  4. stack pointer: real_sp.json holds the depth the original really has at each instruction (measured by
     running it, pipeline/real_sp.py). At each call where IDA's SP change differs from the measured one, a
     user SP change point is set (what Alt+K does), checked by reading IDA's SP back;
  5. re-export: every function of the current export is decompiled again.
Output, next to the IDB: gfx_export_ida_reexport.jsonl, ida_fix_report.json and ida_fix_log.txt. Each step
runs even if an earlier one failed; failures are logged with their traceback.
"""
import json, os, re, sys, time, traceback
import idc, idaapi, ida_auto, ida_bytes, ida_frame, ida_funcs, ida_hexrays, ida_kernwin, ida_lines, ida_nalt
import ida_name, ida_typeinf

DATA = json.loads(r'''__DATA__''')
OUT_DIR = os.path.dirname(idc.get_idb_path()) or os.getcwd()
LOG = []
VIEWPORT_DECL = 'struct D3DVIEWPORT8 { unsigned int X; unsigned int Y; unsigned int Width; unsigned int Height; float MinZ; float MaxZ; };'


def log(*a):
    s = ' '.join(str(x) for x in a); LOG.append(s); print(s)


def add_note(ea, note):
    func = idc.get_func_attr(ea, idc.FUNCATTR_START) == ea
    old = (idc.get_func_cmt(ea, 0) if func else idc.get_cmt(ea, 0)) or ''
    if note not in old:
        new = (old + '\n' + note).strip()
        idc.set_func_cmt(ea, new, 0) if func else idc.set_cmt(ea, new, 0)


# ------------------------------------------------------------------ 1-3: names, prototypes, viewports
def apply_names():
    done, skipped = 0, []
    for k, v in DATA['names'].items():
        ea = int(k, 16); cur = ida_name.get_name(ea)
        if cur == v['name']: continue
        if cur != v['old'] or not ida_name.set_name(ea, v['name'], ida_name.SN_NOWARN | ida_name.SN_NOCHECK):
            skipped.append((k, cur, v['name'])); continue
        add_note(ea, '[name %s 2026-10-02, %s confidence, from the code and the IDA listing] %s'
                 % (v['name'], v['confidence'], v['evidence']))
        done += 1
    log('names: %d applied, %d skipped' % (done, len(skipped)))
    for s in skipped: log('  skipped %s: IDB has %r, wanted %r' % s)


def apply_types():
    done = 0
    for k, v in DATA['types'].items():
        ea = int(k, 16); nm = ida_name.get_name(ea) or 'f'; t = v['type']
        if '(' in t: decl = t.replace('(', ' %s(' % nm, 1) + ';'
        elif '[' in t: decl = t.replace('[', ' %s[' % nm, 1) + ';'
        else: decl = '%s %s;' % (t, nm)
        if not idc.SetType(ea, decl):
            log('  prototype failed %s: %s' % (k, decl)); continue
        add_note(ea, '[type 2026-10-02] %s %s' % (v['why'], v['evidence'])); done += 1
    log('prototypes: %d applied' % done)


def apply_viewports():
    for g in (0x104E1B70, 0x10621904):
        ok = idc.SetType(g, 'D3DVIEWPORT8;')
        if not ok:
            idc.parse_decls(VIEWPORT_DECL, 0)
            ok = idc.SetType(g, 'D3DVIEWPORT8;')
        log('viewport global 0x%X typed D3DVIEWPORT8: %s' % (g, bool(ok)))


# ------------------------------------------------------------------ 4: stack pointer
def is_call(ea):
    return idc.print_insn_mnem(ea) == 'call'


def first_disagreement(real):
    """the first call (address order) across which IDA's SP change differs from the measured one:
    (call, IDA's change, real change). real: {ea: depth}, depth = bytes below the entry SP; IDA's SP falls
    as the stack grows, so a call that pops N changes it by +N."""
    for ea in sorted(real):
        nxt = ea + idc.get_item_size(ea)
        if nxt not in real or not is_call(ea): continue
        a, b = idc.get_spd(ea), idc.get_spd(nxt)
        if a is None or b is None: continue
        if b - a != real[ea] - real[nxt]: return ea, b - a, real[ea] - real[nxt]
    return None


def mismatches(real):
    return sum(1 for ea, d in real.items() if idc.get_spd(ea) is not None and idc.get_spd(ea) != -d)


def set_change(call, value):
    nxt = call + idc.get_item_size(call); pfn = ida_funcs.get_func(call)
    ida_frame.del_stkpnt(pfn, nxt)
    ida_frame.add_user_stkpnt(nxt, value)
    ida_funcs.reanalyze_function(pfn); ida_auto.auto_wait()
    return idc.get_spd(nxt) - idc.get_spd(call)


def fix_sp(report):
    funcs = DATA['real_sp']; n = 0
    for fk, rec in funcs.items():
        n += 1
        if ida_kernwin.user_cancelled(): log('SP: cancelled'); break
        if n % 25 == 0: ida_kernwin.replace_wait_box('SP check %d of %d' % (n, len(funcs)))
        f = int(fk, 16)
        if not ida_funcs.get_func(f): continue
        real = {int(a, 16): d for a, d in rec.items()}
        before = mismatches(real)
        if not before: continue
        fixes = []
        for _ in range(32):
            bad = first_disagreement(real)
            if not bad: break
            call, c_ida, c_real = bad
            got = set_change(call, c_real)
            if got != c_real: got = set_change(call, -c_real)     # the other sign convention
            fixes.append({'call': '0x%08X' % call, 'ida_change_was': c_ida, 'real_change': c_real, 'now': got})
            idc.set_cmt(call, '[sp fix 2026-10-02] this call changes SP by %d (measured by running the original); IDA had %d'
                        % (c_real, c_ida), 0)
            if got != c_real: break
        ida_hexrays.mark_cfunc_dirty(f)
        after = mismatches(real)
        report['sp'][fk] = {'name': idc.get_func_name(f), 'disagreed_before': before, 'disagreed_after': after, 'fixes': fixes}
        log('SP %s %s: %d instructions disagreed, %d after %d fixes' % (fk, idc.get_func_name(f), before, after, len(fixes)))
    log('SP: corrected in %d functions, %d still disagree'
        % (len(report['sp']), sum(1 for r in report['sp'].values() if r['disagreed_after'])))


# ------------------------------------------------------------------ 5: re-export (same records as ida_gfx.export_one)
BAD = re.compile(r'__usercall|__userpurge|JUMPOUT|__asm|__spoils|BUG\(\)|__halt|_UNKNOWN|MEMORY\[|'
                 r'__readfsdword|__writefsdword|__outbyte|__inbyte|__CFSHL__|__SEH_|__try|__except')


def type_decl_closure(t, acc):
    try:
        if t.is_ptr() or t.is_array():
            type_decl_closure(t.get_pointed_object() if t.is_ptr() else t.get_array_element(), acc); return
        if t.is_func():
            fd = ida_typeinf.func_type_data_t()
            if t.get_func_details(fd):
                type_decl_closure(fd.rettype, acc)
                for a in fd: type_decl_closure(a.type, acc)
            return
        n = t.get_type_name()
        if n and n not in acc and (t.is_struct() or t.is_union() or t.is_enum() or t.is_typedef()):
            acc.add(n)
            if t.is_struct() or t.is_union():
                udt = ida_typeinf.udt_type_data_t()
                if t.get_udt_details(udt):
                    for m in udt: type_decl_closure(m.type, acc)
    except Exception:
        pass


def cc_name(fd):
    try: cc = fd.get_cc()
    except Exception: cc = getattr(fd, 'cc', 0)
    return {ida_typeinf.CM_CC_CDECL: 'cdecl', ida_typeinf.CM_CC_STDCALL: 'stdcall', ida_typeinf.CM_CC_THISCALL: 'thiscall',
            ida_typeinf.CM_CC_FASTCALL: 'fastcall'}.get(cc & ida_typeinf.CM_CC_MASK, 'other')


def export_one(ea):
    rec = {'ea': ea, 'name': ida_name.get_name(ea), 'type': idc.get_type(ea) or ''}
    try:
        ida_hexrays.mark_cfunc_dirty(ea)
        cf = ida_hexrays.decompile(ea, flags=ida_hexrays.DECOMP_NO_CACHE)
    except Exception as e:
        cf = None; rec['error'] = str(e)
    if not cf:
        rec['skip'] = 'decompile failed'; return rec
    text = str(cf); rec['text'] = text
    m = BAD.search(text)
    if m: rec['skip'] = 'unsupported construct ' + m.group(0)
    objs = {}; types = set()

    class V(ida_hexrays.ctree_visitor_t):
        def __init__(s): super().__init__(ida_hexrays.CV_FAST)
        def visit_expr(s, e):
            if e.op == ida_hexrays.cot_obj:
                oea = e.obj_ea; nm = ida_name.get_name(oea) or ('unk_%X' % oea)
                fn = ida_funcs.get_func(oea); is_func = bool(fn) and fn.start_ea == oea
                t = ida_typeinf.tinfo_t()
                if not ida_nalt.get_tinfo(t, oea): t = e.type
                try: printed = ida_lines.tag_remove(e.print1(None))
                except Exception: printed = nm
                pr = objs.get(nm, {}).get('printed', [])
                if printed not in pr: pr = pr + [printed]
                objs[nm] = {'ea': oea, 'func': is_func, 'type': str(t), 'printed': pr,
                            'size': t.get_size() if not is_func else 0,
                            'is_str': bool(ida_bytes.is_strlit(ida_bytes.get_flags(oea)))}
                if is_func: objs[nm]['purged'] = idc.get_func_attr(oea, idc.FUNCATTR_ARGSIZE)
                type_decl_closure(t, types)
            type_decl_closure(e.type, types)
            return 0
    V().apply_to(cf.body, None)
    for lv in cf.get_lvars(): type_decl_closure(lv.type(), types)
    type_decl_closure(cf.type, types)
    rec['objs'] = objs; rec['types'] = sorted(types)
    rec['purged'] = idc.get_func_attr(ea, idc.FUNCATTR_ARGSIZE)
    fd = ida_typeinf.func_type_data_t(); cf.type.get_func_details(fd)
    rec['cc'] = cc_name(fd); rec['ret'] = str(fd.rettype)
    rec['args'] = [[a.name, str(a.type), a.type.get_size(),
                    (str(a.type.get_pointed_object()) if a.type.is_ptr() else None),
                    (a.type.get_pointed_object().get_size() if a.type.is_ptr() else None)] for a in fd]
    return rec


def reexport(report):
    out = os.path.join(OUT_DIR, 'gfx_export_ida_reexport.jsonl'); eas = DATA['export']; skipped = 0
    with open(out, 'w') as f:
        for i, ea in enumerate(eas):
            if ida_kernwin.user_cancelled(): log('export: cancelled at %d' % i); break
            if i % 10 == 0: ida_kernwin.replace_wait_box('Re-export %d of %d' % (i, len(eas)))
            try: rec = export_one(ea)
            except Exception as e: rec = {'ea': ea, 'skip': 'export error: %s' % e}
            skipped += 'skip' in rec
            f.write(json.dumps(rec) + '\n')
    report['export'] = {'file': out, 'functions': len(eas), 'skip': skipped}
    log('export: %d functions written to %s (%d marked skip)' % (len(eas), out, skipped))


def main():
    t0 = time.time(); report = {'sp': {}}
    log('ffxi_ida_fix: IDA %s, IDB %s' % (idaapi.get_kernel_version(), idc.get_idb_path()))
    if not ida_hexrays.init_hexrays_plugin(): log('Hex-Rays decompiler is not available'); return
    ida_kernwin.show_wait_box('ffxi_ida_fix')
    try:
        for step in (apply_names, apply_types, apply_viewports, lambda: ida_auto.auto_wait(),
                     lambda: fix_sp(report), lambda: reexport(report)):
            try: step()
            except Exception: log('STEP FAILED:\n' + traceback.format_exc())
    finally:
        ida_kernwin.hide_wait_box()
        json.dump(report, open(os.path.join(OUT_DIR, 'ida_fix_report.json'), 'w'), indent=1)
        open(os.path.join(OUT_DIR, 'ida_fix_log.txt'), 'w').write('\n'.join(LOG) + '\n')
        log('ffxi_ida_fix: done in %.0f s; results in %s' % (time.time() - t0, OUT_DIR))


main()
