"""gen_sdk.py -- the generated part of the SDK (sdk/include/xikit_game.hpp), from the tree and the kit's manifest.

xikit_game.hpp includes every header of the tree (classes, free functions, orig::, globals) and gives, for every
reconstructed function the tree declares (tree/placement.json), a typed pointer to the game's entry of it:

    xigame::CDx__DrawFadeQuad()         -> int (__thiscall *)(CDx *, int, int), at 0x1000A820 + the load delta

(a call through it runs whatever is at the entry: the game's code, the kit's swap, or a mod's hook), and, for the
functions of the manifest, whether a mod can hook them (xihook::CDx__DrawFadeQuad = flags; see the comment there).
The type is the tree's declaration (decltype), so it is checked by the compiler, not written out here. A function
whose declaration does not compile in this form is left out and listed at the end of the header.

    python3 sdk/gen_sdk.py            (writes sdk/include/xikit_game.hpp; uses MinGW to check it compiles)"""
import json, os, re, subprocess, sys, tempfile
H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(H, '..'); TI = os.path.join(ROOT, 'tree', 'include')
OUT = os.path.join(H, 'include', 'xikit_game.hpp')
CXX = os.environ.get('CXX', 'i686-w64-mingw32-g++')


def ident(sym): return re.sub(r'\W', '_', sym.replace('::', '__'))


def main():
    place = json.load(open(os.path.join(ROOT, 'tree', 'placement.json')))
    man = {}
    for l in open(os.path.join(ROOT, 'kit', 'xikit', 'dist', 'xikit_manifest.txt')):
        if l[0] in '#!' or not l.strip(): continue
        p = l.split(); t = next((x[2:] for x in p if x.startswith('T=')), '-')
        man[0x10000000 + int(p[0], 16)] = (int(p[1]), p[5], t)
    heads = sorted(h for h in os.listdir(TI) if h.endswith('.hpp') and not h.startswith(('gfx_', 'xi_')))
    ents = sorted((int(a, 16), v['symbol']) for a, v in place.items())
    def text(ok, dropped):
        o = ['// xikit_game.hpp -- GENERATED by sdk/gen_sdk.py from tree/placement.json and the kit manifest; do not edit.',
             '// The tree\'s declarations, and typed pointers to the game\'s entries of the reconstructed functions.',
             '#pragma once', '#include "gfx_all.hpp"']
        o += ['#include "%s"' % h for h in heads]
        o += ['#include "xikit_sdk_types.hpp"', '', 'namespace xigame {',
              '// the game\'s entry of each reconstructed function, typed by the tree\'s declaration']
        for a, s in ok:
            o.append('inline ::xikit::fn<decltype(&::%s)> %s() { return reinterpret_cast< ::xikit::fn<decltype(&::%s)> >(XI_GAME(0x%08Xu)); }'
                     % (s, ident(s), s, a))
        o += ['}', '', 'namespace xihook {',
              '// the functions in the kit\'s manifest: flags 1 SEH, 2 speedfix site, 4 gate coverage incomplete, 8 register',
              '// input its declaration lacks (the kit refuses a hook of it);',
              '// TRAMP = 1 if the hook\'s previous is a trampoline to the game\'s own code, 0 if it is the reconstruction']
        for a, s in ok:
            if a in man:
                f, n, t = man[a]
                o.append('constexpr unsigned %s = %d, %s_TRAMP = %d;  // "%s" 0x%08X' % (ident(s), f, ident(s), t != '-', n, a))
        o += ['}']
        if dropped: o += ['', '// left out (their declaration does not compile as decltype(&name)):'] + ['//   0x%08X %s' % x for x in dropped]
        return '\n'.join(o) + '\n'
    ok, dropped = list(ents), []
    for _ in range(20):
        open(OUT, 'w').write(text(ok, dropped))
        with tempfile.TemporaryDirectory() as d:
            src = os.path.join(d, 't.cpp'); open(src, 'w').write('#include "xikit_game.hpp"\n')
            r = subprocess.run([CXX, '-std=c++17', '-fsyntax-only', '-DXI_INGAME', '-fpermissive', '-w', '-fmax-errors=0',
                                '-I' + os.path.join(H, 'include'), '-I' + TI, src], capture_output=True, text=True)
        if r.returncode == 0: break
        bad = {int(m) for m in re.findall(r'xikit_game\.hpp:(\d+):\d+: error', r.stderr)}
        if not bad: sys.exit(r.stderr[-3000:])
        lines = text(ok, dropped).split('\n')
        names = {re.search(r'decltype\(&::([^)]+)\)', lines[b - 1]).group(1) for b in bad if 'decltype' in lines[b - 1]}
        if not names: sys.exit(r.stderr[-3000:])
        dropped += [x for x in ok if x[1] in names]; ok = [x for x in ok if x[1] not in names]
    print('%s: %d functions typed, %d hookable, %d left out' % (OUT, len(ok), sum(a in man for a, _ in ok), len(dropped)))


if __name__ == '__main__':
    main()
